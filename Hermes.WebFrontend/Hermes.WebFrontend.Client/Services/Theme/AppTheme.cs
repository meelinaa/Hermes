namespace Hermes.WebFrontend.Client.Services.Theme;

/// <summary>
/// Defines user interface color scheme themes.
/// </summary>
public enum AppTheme
{
    /// <summary>Follows operating system dark/light color scheme preference.</summary>
    System,

    /// <summary>Forces Swiss minimalist light color scheme.</summary>
    Light,

    /// <summary>Forces Swiss high-contrast dark color scheme.</summary>
    Dark
}
